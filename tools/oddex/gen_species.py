BANNER = '// Generated by tools/oddex/gen_species.py from content/. Do not edit.\n'

NAME_MAX = 12
CATEGORY_MAX = 12
DEX_LINE_MAX = 42
DEX_LINES_MAX = 4
STAT_FIELDS = [('hp', 'baseHP'), ('atk', 'baseAttack'), ('def', 'baseDefense'),
               ('spe', 'baseSpeed'), ('spa', 'baseSpAttack'), ('spd', 'baseSpDefense')]
EV_FIELDS = {'hp': 'HP', 'atk': 'Attack', 'def': 'Defense', 'spe': 'Speed', 'spa': 'SpAttack', 'spd': 'SpDefense'}


class SpeciesError(Exception):
    pass


def camel(species_id):
    return ''.join(part.capitalize() for part in species_id.split('_'))


def known_identifiers():
    """Identifiers defined anywhere under game/include, excluding everything we generate."""
    idents = set()
    region = re.compile(r'// oddex:([\w-]+) begin.*?// oddex:\1 end', re.S)
    for header in (GAME / 'include').rglob('*.h'):
        if header.name.startswith('oddex_'):
            continue
        text = region.sub('', header.read_text(encoding='utf-8', errors='ignore'))
        idents.update(re.findall(r'\b[A-Z][A-Z0-9_]+\b', text))
    return idents


def c_string(text):
    return text.replace('\\', '\\\\').replace('"', '\\"')


SPRITE_FILES = {  # name: (width, height, max colours incl. transparent)
    'anim_front.png': (64, 128, 16), 'back.png': (64, 64, 16), 'icon.png': (32, 64, 16),
    'overworld.png': (192, 32, 16), 'footprint.png': (16, 16, 2),
}


def round8(n):
    return (n + 7) // 8 * 8


def read_jasc(path):
    rows = path.read_text().split()
    if rows[:2] != ['JASC-PAL', '0100']:
        raise ValueError('not a JASC-PAL file')
    return [tuple(int(v) for v in rows[3 + i * 3: 6 + i * 3]) for i in range(int(rows[2]))]


def inspect_graphics(s, errors):
    """Check the sprite files against GBA limits and fill in values derivable from them:
    front/back size and Y offset (from the drawn bounding box) and the icon palette
    (by matching icon.png's palette to graphics/pokemon/icon_palettes/pal0..5)."""
    f, g = s['_file'], s['graphics']
    gdir = GAME / g['dir']
    imgs = {}
    for name, (w, h, colors) in SPRITE_FILES.items():
        try:
            img = read_png(gdir / name)
        except ValueError as e:
            errors.append(f'{f}: {e}')
            continue
        if (img.width, img.height) != (w, h):
            errors.append(f'{f}: {g["dir"]}/{name} is {img.width}x{img.height}, expected {w}x{h}')
        top = max((max(row) for row in img.rows), default=0)
        if top >= colors:
            errors.append(f'{f}: {g["dir"]}/{name} uses colour index {top}; GBA allows {colors} (index 0 is transparent)')
        imgs[name] = img
    for name in ('normal.pal', 'shiny.pal', 'overworld_normal.pal', 'overworld_shiny.pal'):
        try:
            if len(read_jasc(gdir / name)) != 16:
                errors.append(f'{f}: {g["dir"]}/{name} must have 16 colours')
        except (ValueError, IndexError) as e:
            errors.append(f'{f}: {g["dir"]}/{name}: {e}')
    if 'anim_front.png' in imgs and 'back.png' in imgs:
        front, back = imgs['anim_front.png'], imgs['back.png']
        boxes = [b for b in (front.bbox(0, 64), front.bbox(64, 64)) if b]
        bbox = back.bbox()
        if not boxes or not bbox:
            errors.append(f'{f}: front or back sprite is empty')
        else:
            fw = max(b[2] for b in boxes) - min(b[0] for b in boxes) + 1
            fh = max(b[3] for b in boxes) - min(b[1] for b in boxes) + 1
            g.setdefault('front_size', [min(64, round8(fw)), min(64, round8(fh))])
            g.setdefault('front_y_offset', 63 - max(b[3] for b in boxes))
            g.setdefault('back_size', [min(64, round8(bbox[2] - bbox[0] + 1)), min(64, round8(bbox[3] - bbox[1] + 1))])
            g.setdefault('back_y_offset', 63 - bbox[3])
    if 'icon.png' in imgs:
        icon_pal = imgs['icon.png'].palette[:16]
        matches = [i for i in range(6)
                   if read_jasc(GAME / f'graphics/pokemon/icon_palettes/pal{i}.pal')[:len(icon_pal)] == icon_pal]
        if 'icon_palette' in g:
            if g['icon_palette'] not in matches:
                errors.append(f'{f}: icon.png colours do not match icon palette {g["icon_palette"]} '
                              f'(matches: {matches or "none"})')
        elif matches:
            g['icon_palette'] = matches[0]
        else:
            errors.append(f'{f}: icon.png must use one of graphics/pokemon/icon_palettes/pal0..5')


def validate(all_species, roles, regional, idents, existing=None):
    """`existing` is the slot order currently in species.h (default: read it)."""
    errors = []
    ids = [s['id'] for s in all_species]
    renamed = renamed_ids(all_species)
    if existing is None:
        existing = existing_slots()

    # previous_ids must map every old slot to exactly one species, and each species to at
    # most one slot: two TOMLs claiming the same old id would silently cost one of them its
    # number, and one TOML claiming two live slots would emit SPECIES_<ID> twice.
    claimed = {}
    for s in all_species:
        for old in s.get('previous_ids', []):
            if old in claimed and claimed[old] is not s:
                errors.append(f'{s["_file"]}: previous id {old} is also claimed by {claimed[old]["_file"]}')
            claimed.setdefault(old, s)
        slots = [i for i in [s['id']] + s.get('previous_ids', []) if i in existing]
        if len(set(slots)) > 1:
            numbers = ', '.join(f'{i} (#{CUSTOM_START + 1 + existing.index(i)})' for i in slots)
            errors.append(f'{s["_file"]}: id and previous_ids match more than one slot in species.h: '
                          f'{numbers}; a species can keep only one number')

    def need(spec, prefix, name, what):
        if f'{prefix}{name}' not in idents:
            errors.append(f'{spec["_file"]}: unknown {what} {prefix}{name}')

    for s in all_species:
        f = s['_file']
        if not re.fullmatch(r'[A-Z][A-Z0-9_]*', s['id']):
            errors.append(f'{f}: id must be UPPER_SNAKE_CASE')
        if ids.count(s['id']) > 1:
            errors.append(f'{f}: duplicate id {s["id"]}')
        for table in ('dex', 'learnset', 'graphics', 'design'):
            if 'evolutions' in s.get(table, {}):
                errors.append(f'{f}: evolutions is inside [{table}]; it must be a top-level key '
                              'written before the first [table] header')
        for old in s.get('previous_ids', []):
            if old in ids:
                errors.append(f'{f}: previous id {old} is still used by another species')
        if f'SPECIES_{s["id"]}' in idents:
            errors.append(f'{f}: SPECIES_{s["id"]} already exists in vanilla; pick another id')
        if len(s['name']) > NAME_MAX:
            errors.append(f'{f}: name longer than {NAME_MAX}')
        if len(s['category']) > CATEGORY_MAX:
            errors.append(f'{f}: category longer than {CATEGORY_MAX}')
        lines = s['dex']['text'].strip('\n').split('\n')
        if len(lines) > DEX_LINES_MAX or any(len(line) > DEX_LINE_MAX for line in lines):
            errors.append(f'{f}: dex text must be at most {DEX_LINES_MAX} lines of {DEX_LINE_MAX} characters')
        if s['base_stats'].get('hp', 0) <= 0:
            errors.append(f'{f}: base hp must be > 0 (baseHP == 0 means "species disabled")')
        for t in s['types']:
            need(s, 'TYPE_', t, 'type')
        for a in s['abilities']:
            need(s, 'ABILITY_', a, 'ability')
        for g in s['egg_groups']:
            need(s, 'EGG_GROUP_', g, 'egg group')
        need(s, 'GROWTH_', s['growth_rate'], 'growth rate')
        need(s, 'BODY_COLOR_', s['body_color'], 'body color')
        need(s, 'CRY_', s['cry'], 'cry')
        for _, move in s['learnset']['level']:
            need(s, 'MOVE_', move, 'move')
        for move in s['learnset'].get('teachable', []) + s['learnset'].get('egg', []):
            need(s, 'MOVE_', move, 'move')
        for evo in s.get('evolutions', []):
            need(s, 'EVO_', evo['method'], 'evolution method')
            # Only into another original: vanilla species are disabled in plan B (a vanilla
            # target would hit the disabled-species assert on level up).
            if evo['into'] not in ids:
                errors.append(f'{f}: evolves into {evo["into"]}, which is not an oddex species '
                              f'(content/species/*.toml){old_name_hint(evo["into"], renamed)}')
        g = s['graphics']
        need(s, 'ANIM_', g['front_anim'], 'front animation')
        need(s, 'BACK_ANIM_', g['back_anim'], 'back animation')
        need(s, 'PKMN_JUMP_TYPE_', g['jump'], 'jump type')
        need(s, 'SHADOW_SIZE_', g['shadow']['size'], 'shadow size')
        gdir = GAME / g['dir']
        missing = [name for name in ('anim_front.png', 'back.png', 'icon.png', 'footprint.png', 'overworld.png',
                                     'normal.pal', 'shiny.pal', 'overworld_normal.pal', 'overworld_shiny.pal')
                   if not (gdir / name).exists()]
        errors += [f'{f}: missing {g["dir"]}/{name}' for name in missing]
        if not missing:
            inspect_graphics(s, errors)
    rel = REGIONAL_DEX.relative_to(ROOT)
    for sid in sorted(set(regional)):
        if regional.count(sid) > 1:
            errors.append(f'{rel}: {sid} listed more than once')
        if sid not in ids:
            errors.append(f'{rel}: {sid} is not an original species{old_name_hint(sid, renamed)}')
    for sid in ids:
        if sid not in regional:
            errors.append(f'{rel}: {sid} is missing from the regional Pokedex order')
    for role, target in roles.items():
        if not re.fullmatch(r'[A-Z][A-Z0-9_]*', role):
            errors.append(f'{ROLES.relative_to(ROOT)}: role {role} must be UPPER_SNAKE_CASE')
        if target not in ids and f'SPECIES_{target}' not in idents:
            errors.append(f'{ROLES.relative_to(ROOT)}: role {role} points to unknown species '
                          f'{target}{old_name_hint(target, renamed)}')
    if errors:
        raise SpeciesError('\n'.join(errors))


def warnings(all_species, regional):
    """Data that builds but is probably a mistake. Returns messages; main() prints them."""
    out = []
    by_id = {s['id']: s for s in all_species}
    parent = {e['into']: s['id'] for s in all_species for e in s.get('evolutions', []) if e['into'] in by_id}
    for sid, pid in parent.items():
        s = by_id[sid]
        levels = s['learnset']['level']
        if any(lv == 0 for lv, _ in levels):
            continue
        # P_EVOLUTION_LEVEL_1_LEARN is GEN_LATEST (include/config/pokemon.h), so evolving skips level 1
        # moves (src/pokemon.c): a level 1 move the previous stage never learns is only relearnable.
        known = {m for _, m in by_id[pid]['learnset']['level']}
        new = [m for lv, m in levels if lv == 1 and m not in known]
        if new:
            out.append(f'{s["_file"]}: evolves from {pid} but its new level 1 moves ({", ".join(new)}) '
                       'are not taught on evolution; write the evolution move as level 0')
    # Each evolution line together and in stage order in the regional Pokedex.
    rel = REGIONAL_DEX.relative_to(ROOT)
    for sid, pid in parent.items():
        if sid in regional and pid in regional and regional.index(sid) != regional.index(pid) + 1:
            siblings = [e['into'] for e in by_id[pid].get('evolutions', [])]
            if len(siblings) == 1:   # branched lines (two evolutions) cannot all follow their parent
                out.append(f'{rel}: {sid} should come right after {pid}, its previous stage')
    return out


def fill_region(text, name, body):
    """Replace the lines between '// oddex:<name> begin' and '// oddex:<name> end'."""
    pattern = re.compile(rf'(^[ \t]*// oddex:{name} begin[^\n]*\n)(.*?)(^[ \t]*// oddex:{name} end)', re.M | re.S)
    if not pattern.search(text):
        raise SpeciesError(f'marker "oddex:{name}" not found')
    return pattern.sub(lambda m: m.group(1) + body + m.group(3), text, count=1)


def gen_species_h(all_species, text):
    return fill_region(text, 'species-ids', ''.join(f'    SPECIES_{s["id"]},\n' for s in all_species))


def gen_pokedex_h(all_species, regional, text):
    text = fill_region(text, 'dex-ids', ''.join(f'    NATIONAL_DEX_{s["id"]},\n' for s in all_species))
    count = ''
    if all_species:
        count = f'#undef NATIONAL_DEX_COUNT\n#define NATIONAL_DEX_COUNT  NATIONAL_DEX_{all_species[-1]["id"]}\n'
    text = fill_region(text, 'dex-count', count)
    # Original species are appended after the vanilla Hoenn list while Gen 3 is enabled,
    # and are the whole regional dex once it is disabled.
    order = ''.join(f' \\\n    F({sid})' for sid in regional)
    body = f'#define ODDEX_REGIONAL_DEX_ORDER(F){order}\n'
    if regional:
        body += f'#define HOENN_DEX_LAST HOENN_DEX_{regional[-1]}\n'
    else:
        body += '#if P_GEN_3_POKEMON\n#define HOENN_DEX_LAST HOENN_DEX_DEOXYS\n#else\n#define HOENN_DEX_LAST HOENN_DEX_NONE\n#endif\n'
    return fill_region(text, 'regional-dex', body)


def gen_roles(roles):
    out = [BANNER, '#ifndef GUARD_CONSTANTS_ODDEX_SPECIES_H\n#define GUARD_CONSTANTS_ODDEX_SPECIES_H\n\n',
           '// Story/gameplay roles. Code, scripts, trainers.party and wild_encounters.json refer to\n',
           '// these instead of a concrete species, so recasting a role is a one-line content change.\n']
    for role, target in roles.items():
        out.append(f'#define SPECIES_ODDEX_{role:<24} SPECIES_{target}\n')
    out.append('\n#endif // GUARD_CONSTANTS_ODDEX_SPECIES_H\n')
    return ''.join(out)


def gen_data(all_species):
    out = [BANNER, '// Included from src/pokemon.c right before data/pokemon/species_info.h.\n']
    for s in all_species:
        c = camel(s['id'])
        g = s['graphics']
        d = g['dir']
        out.append(f'\n// {s["name"]}\n')
        out.append(f'static const struct LevelUpMove s{c}LevelUpLearnset[] = {{\n')
        for level, move in s['learnset']['level']:
            out.append(f'    LEVEL_UP_MOVE({level:>2}, MOVE_{move}),\n')
        out.append('    LEVEL_UP_END\n};\n')
        if s['learnset'].get('egg'):
            out.append(f'static const u16 s{c}EggMoveLearnset[] = {{\n')
            out += [f'    MOVE_{m},\n' for m in s['learnset']['egg']]
            out.append('    MOVE_UNAVAILABLE,\n};\n')
        out.append(f'const u32 gMonFrontPic_{c}[] = INCGFX_U32("{d}/anim_front.png", ".4bpp.smol");\n')
        out.append(f'const u32 gMonBackPic_{c}[] = INCGFX_U32("{d}/back.png", ".4bpp.smol");\n')
        out.append(f'const u16 gMonPalette_{c}[] = INCGFX_U16("{d}/normal.pal", ".gbapal");\n')
        out.append(f'const u16 gMonShinyPalette_{c}[] = INCGFX_U16("{d}/shiny.pal", ".gbapal");\n')
        out.append(f'const u8 gMonIcon_{c}[] = INCGFX_U8("{d}/icon.png", ".4bpp");\n')
        out.append('#if P_FOOTPRINTS\n')
        out.append(f'const u8 gMonFootprint_{c}[] = INCGFX_U8("{d}/footprint.png", ".1bpp");\n')
        out.append('#endif\n#if OW_POKEMON_OBJECT_EVENTS\n')
        out.append(f'const u32 gObjectEventPic_{c}[] = INCGFX_COMP("{d}/overworld.png", ".4bpp", "-mwidth 4 -mheight 4");\n')
        out.append('#if OW_PKMN_OBJECTS_SHARE_PALETTES == FALSE\n')
        out.append(f'const u16 gOverworldPalette_{c}[] = INCGFX_U16("{d}/overworld_normal.pal", ".gbapal");\n')
        out.append(f'const u16 gShinyOverworldPalette_{c}[] = INCGFX_U16("{d}/overworld_shiny.pal", ".gbapal");\n')
        out.append('#endif\n')
        out.append(f'static const struct SpriteFrameImage sPicTable_{c}[] = {{\n')
        out.append(f'    overworld_ascending_frames(gObjectEventPic_{c}, 4, 4),\n}};\n')
        out.append('#endif\n')
    return ''.join(out)


def gen_info(all_species):
    out = [BANNER, '// Included inside gSpeciesInfo[] from src/data/pokemon/species_info.h.\n']
    for s in all_species:
        c = camel(s['id'])
        g = s['graphics']
        st = s['base_stats']
        out.append(f'\n    [SPECIES_{s["id"]}] =\n    {{\n')
        for key, field in STAT_FIELDS:
            out.append(f'        .{field:<13} = {st[key]},\n')
        out.append(f'        .types = MON_TYPES({", ".join("TYPE_" + t for t in s["types"])}),\n')
        out.append(f'        .catchRate = {s["catch_rate"]},\n')
        out.append(f'        .expYield = {s["exp_yield"]},\n')
        for key, value in s.get('ev_yield', {}).items():
            out.append(f'        .evYield_{EV_FIELDS[key]} = {value},\n')
        if s['gender'] == 'GENDERLESS':
            out.append('        .genderRatio = MON_GENDERLESS,\n')
        else:
            out.append(f'        .genderRatio = PERCENT_FEMALE({s["gender"]}),\n')
        out.append(f'        .eggCycles = {s["egg_cycles"]},\n')
        out.append('        .friendship = STANDARD_FRIENDSHIP,\n')
        out.append(f'        .growthRate = GROWTH_{s["growth_rate"]},\n')
        out.append(f'        .eggGroups = MON_EGG_GROUPS({", ".join("EGG_GROUP_" + e for e in s["egg_groups"])}),\n')
        out.append(f'        .abilities = {{ {", ".join("ABILITY_" + a for a in s["abilities"])} }},\n')
        out.append(f'        .bodyColor = BODY_COLOR_{s["body_color"]},\n')
        out.append(f'        .speciesName = _("{c_string(s["name"])}"),\n')
        out.append(f'        .cryId = CRY_{s["cry"]},\n')
        out.append(f'        .natDexNum = NATIONAL_DEX_{s["id"]},\n')
        out.append(f'        .categoryName = _("{c_string(s["category"])}"),\n')
        out.append(f'        .height = {s["dex"]["height"]},\n')
        out.append(f'        .weight = {s["dex"]["weight"]},\n')
        lines = s['dex']['text'].strip('\n').split('\n')
        out.append('        .description = COMPOUND_STRING(\n')
        out += [f'            "{c_string(line)}{chr(92) + "n" if i < len(lines) - 1 else ""}"\n'
                for i, line in enumerate(lines)]
        out[-1] = out[-1].rstrip('\n') + '),\n'
        sc = s['dex']['scale']
        out.append(f'        .pokemonScale = {sc["pokemon"]},\n        .pokemonOffset = {sc["pokemon_offset"]},\n')
        out.append(f'        .trainerScale = {sc["trainer"]},\n        .trainerOffset = {sc["trainer_offset"]},\n')
        out.append(f'        .frontPic = gMonFrontPic_{c},\n')
        out.append(f'        .frontPicSize = MON_COORDS_SIZE({g["front_size"][0]}, {g["front_size"][1]}),\n')
        out.append(f'        .frontPicYOffset = {g["front_y_offset"]},\n')
        # ANIM_FRAMES pastes ANIMCMD_END straight after the arguments, so each frame needs its comma.
        frames = ''.join(f'\n            ANIMCMD_FRAME({i}, {t}),' for i, t in g['front_frames'])
        out.append(f'        .frontAnimFrames = ANIM_FRAMES({frames}\n        ),\n')
        out.append(f'        .frontAnimId = ANIM_{g["front_anim"]},\n')
        out.append(f'        .backPic = gMonBackPic_{c},\n')
        out.append(f'        .backPicSize = MON_COORDS_SIZE({g["back_size"][0]}, {g["back_size"][1]}),\n')
        out.append(f'        .backPicYOffset = {g["back_y_offset"]},\n')
        out.append(f'        .backAnimId = BACK_ANIM_{g["back_anim"]},\n')
        out.append(f'        .palette = gMonPalette_{c},\n        .shinyPalette = gMonShinyPalette_{c},\n')
        out.append(f'        .iconSprite = gMonIcon_{c},\n        .iconPalIndex = {g["icon_palette"]},\n')
        out.append(f'        .pokemonJumpType = PKMN_JUMP_TYPE_{g["jump"]},\n')
        sh = g['shadow']
        out.append(f'        SHADOW({sh["x"]}, {sh["y"]}, SHADOW_SIZE_{sh["size"]})\n')
        out.append(f'        FOOTPRINT({c})\n')
        ow = g['overworld']
        out.append(f'        OVERWORLD(\n            sPicTable_{c},\n            SIZE_{ow["size"]},\n'
                   f'            SHADOW_SIZE_{ow["shadow"]},\n            TRACKS_{ow["tracks"]},\n'
                   f'            sAnimTable_Following,\n            gOverworldPalette_{c},\n'
                   f'            gShinyOverworldPalette_{c}\n        )\n')
        out.append(f'        .levelUpLearnset = s{c}LevelUpLearnset,\n')
        out.append(f'        .teachableLearnset = s{c}TeachableLearnset,\n')
        egg = f's{c}EggMoveLearnset' if s['learnset'].get('egg') else 'sNoneEggMoveLearnset'
        out.append(f'        .eggMoveLearnset = {egg},\n')
        if s.get('evolutions'):
            evos = ', '.join(f'{{EVO_{e["method"]}, {e["param"]}, SPECIES_{e["into"]}}}' for e in s['evolutions'])
            out.append(f'        .evolutions = EVOLUTION({evos}),\n')
        out.append('    },\n')
    return ''.join(out)


def gen_learnables(all_species, current_text):
    data = json.loads(current_text)
    for s in all_species:
        for old in s.get('previous_ids', []):
            data.pop(old, None)
    for s in all_species:
        data[s['id']] = sorted(f'MOVE_{m}' for m in s['learnset'].get('teachable', []))
    return json.dumps(data, indent=2)


CUSTOM_START = 1572  # SPECIES_CUSTOM_START (= SPECIES_GLIMMORA_MEGA) in expansion 1.17.2


def existing_slots():
    """Original species ids in their current species.h order (index 0 = CUSTOM_START + 1)."""
    text = (GAME / 'include/constants/species.h').read_text()
    region = re.search(r'// oddex:species-ids begin[^\n]*\n(.*?)// oddex:species-ids end', text, re.S)
    return re.findall(r'SPECIES_(\w+),', region.group(1)) if region else []


def stable_order(all_species):
    """Species ids are saved in save files, so keep the order already in species.h and
    append new species at the end (sorted by id). Renaming keeps the slot via previous_ids;
    removing a species shifts the ones after it."""
    # A renamed species lists its old ids in previous_ids and keeps the old slot (and number).
    # A species claiming several live slots keeps the first here; validate() rejects it.
    renamed = renamed_ids(all_species)
    existing = []
    for i in existing_slots():
        if renamed.get(i, i) not in existing:
            existing.append(renamed.get(i, i))
    by_id = {s['id']: s for s in all_species}
    kept = [by_id[i] for i in existing if i in by_id]
    removed = [i for i in existing if i not in by_id]
    if removed:
        print(f'gen_species: warning: removed {", ".join(removed)}; later species ids shift', file=sys.stderr)
    return kept + sorted((s for s in all_species if s['id'] not in existing), key=lambda s: s['id'])


def vanilla_enabled():
    text = (GAME / 'include/config/species_enabled.h').read_text()
    return bool(re.search(r'^#define P_GEN_3_POKEMON\s+TRUE', text, re.M))


def dial_path(start, goal, allowed, maximum):
    """Shortest list of (digit, +1/-1) presses in the sprite visualizer's 4-digit species
    selector from start to goal, only passing through values in `allowed`."""
    from collections import deque
    prev = {start: None}
    queue = deque([start])
    while queue:
        value = queue.popleft()
        if value == goal:
            break
        digits = f'{value:04d}'
        for pos in range(4):
            for step in (1, -1):
                d = int(digits[pos]) + step
                if not 0 <= d <= 9:
                    continue
                nxt = int(digits[:pos] + str(d) + digits[pos + 1:])
                if 1 <= nxt <= maximum and nxt in allowed and nxt not in prev:
                    prev[nxt] = (value, pos, step)
                    queue.append(nxt)
    if goal not in prev:
        raise SpeciesError(f'gallery: cannot dial species {goal} from {start}')
    moves = []
    while prev[goal]:
        value, pos, step = prev[goal]
        moves.append((pos, step))
        goal = value
    return moves[::-1]


def gen_gallery(all_species):
    """Headless script: to_starter, then every original species (normal + shiny) in the
    summary screen's sprite visualizer. Re-generated with the species list."""
    first = CUSTOM_START + 1
    ids = {s['id']: first + i for i, s in enumerate(all_species)}
    maximum = first + len(all_species) - 1
    oddex_ids = set(ids.values())
    vanilla = vanilla_enabled()
    start = 1 if vanilla else first  # the visualizer opens on the first enabled species
    out = ['# Generated by tools/oddex/gen_species.py. Do not edit.\n',
           '# Every original species in the sprite visualizer (front at the enemy position, back,\n',
           '# icon, footprint), normal then shiny. The visualizer is reopened so it starts on the\n',
           f'# first enabled species ({"0001: vanilla generations on" if vanilla else f"{first}: vanilla off"}).\n',
           'include to_starter.txt\n',
           '# Leaving the visualizer returns to the start menu; reopen party -> summary -> SELECT.\n',
           'press B 2 120\n', 'press A 2 90\n', 'press A 2 40\n', 'press A 2 90\n', 'press SELECT 2 120\n']
    cursor, value = 0, start
    for s in all_species:
        target = ids[s['id']]
        allowed = oddex_ids | ({target} if not vanilla else set(range(1, maximum + 1)))
        for pos, step in dial_path(value, target, allowed, maximum):
            while cursor != pos:
                out.append('press RIGHT 2 10\n' if pos > cursor else 'press LEFT 2 10\n')
                cursor += 1 if pos > cursor else -1
            out.append(f'press {"UP" if step > 0 else "DOWN"} 2 20\n')
        value = target
        name = f'gallery/{target:04d}_{s["id"].lower()}'
        out += ['wait 120\n', f'shot {name}.png\n',
                'press START 2 120\n', f'shot {name}_shiny.png\n', 'press START 2 120\n']
    return ''.join(out)


def vanilla_hoenn_count():
    """How many vanilla entries precede the originals in the Hoenn dex: VANILLA_HOENN_DEX_ORDER
    has entries that depend on config (HOENN_DEX_IF), so let the ARM preprocessor expand it."""
    cpp = shutil.which('arm-none-eabi-cpp')
    if not cpp:
        raise SpeciesError('arm-none-eabi-cpp not found; run `. tools/env.sh` first')
    src = '#include "global.h"\n#define ODDEX_ENTRY(x) @x\nODDEX_BEGIN VANILLA_HOENN_DEX_ORDER(ODDEX_ENTRY) ODDEX_END\n'
    out = subprocess.run([cpp, '-P', '-I', 'include', '-I', '.', '-'], input=src, capture_output=True, text=True,
                         cwd=GAME).stdout
    m = re.search(r'ODDEX_BEGIN(.*)ODDEX_END', out, re.S)
    if not m:
        raise SpeciesError('could not expand VANILLA_HOENN_DEX_ORDER with arm-none-eabi-cpp')
    return m.group(1).count('@')


def gen_dex_script(regional):
    """Headless script: every original species' Pokedex entry page (category, height, weight,
    text), in regional dex order. The debug menu sets every Pokedex flag and gives the Pokedex;
    in the Hoenn list RIGHT pages down 7 entries, so the first original is RIGHT x (n-1)//7 then
    DOWN x (n-1)%7 from No.001."""
    vanilla = vanilla_hoenn_count() if vanilla_enabled() else 0
    first = vanilla + 1
    out = ['# Generated by tools/oddex/gen_species.py. Do not edit.\n',
           "# Every original species' Pokedex entry page (category, height, weight, text): to_littleroot,\n",
           '# then the debug menu (hold R, press START; debug builds only) -> Flags & Vars sets every\n',
           '# Pokedex flag and toggles the Pokedex on, and the Hoenn list is paged down to the first\n',
           f'# original (No.{first:03d}).\n',
           'include to_littleroot.txt\n', 'wait 60\n',
           'press R+START 2 60\n', 'repeat 8 press DOWN 2 12\n', 'press A 2 60\n',
           '# Pokedex Flags All (closes the menu)\n', 'repeat 2 press DOWN 2 12\n', 'press A 2 120\n',
           'press R+START 2 60\n', 'repeat 8 press DOWN 2 12\n', 'press A 2 60\n',
           '# Toggle Pokedex (stays in the menu)\n', 'repeat 4 press DOWN 2 12\n', 'press A 2 120\n',
           'press B 2 60\n', 'press B 2 60\n',
           'press START 2 60\n', 'press A 2 240\n']
    if (first - 1) // 7:
        out.append(f'repeat {(first - 1) // 7} press RIGHT 2 20\n')
    if (first - 1) % 7:
        out.append(f'repeat {(first - 1) % 7} press DOWN 2 20\n')
    for i, sid in enumerate(regional):
        out += ['press A 2 150\n', f'shot dex/{first + i:03d}_{sid.lower()}.png\n', 'press B 2 90\n', 'press DOWN 2 20\n']
    return ''.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--check', action='store_true', help='fail if generated files are out of date')
    args = parser.parse_args()

    all_species = stable_order(load_species())
    roles = load_roles()
    regional = load_regional_dex()
    try:
        validate(all_species, roles, regional, known_identifiers())
    except SpeciesError as e:
        sys.exit(f'gen_species: invalid species data:\n{e}')
    for w in warnings(all_species, regional):
        print(f'gen_species: warning: {w}', file=sys.stderr)

    learnables = GAME / 'src/data/pokemon/all_learnables.json'
    species_h = GAME / 'include/constants/species.h'
    pokedex_h = GAME / 'include/constants/pokedex.h'
    try:
        outputs = {
            species_h: gen_species_h(all_species, species_h.read_text()),
            pokedex_h: gen_pokedex_h(all_species, regional, pokedex_h.read_text()),
        }
    except SpeciesError as e:
        sys.exit(f'gen_species: {e}')
    outputs |= {
        GAME / 'include/constants/oddex_species.h': gen_roles(roles),
        GAME / 'src/data/pokemon/oddex_data.h': gen_data(all_species),
        GAME / 'src/data/pokemon/species_info/oddex_families.h': gen_info(all_species),
        ROOT / 'tools/headless/scripts/oddex_gallery.txt': gen_gallery(all_species),
        ROOT / 'tools/headless/scripts/oddex_dex.txt': gen_dex_script(regional),
        learnables: gen_learnables(all_species, learnables.read_text()),
    }
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    if args.check:
        for p in stale:
            print(f'stale: {p.relative_to(ROOT)}', file=sys.stderr)
        sys.exit(1 if stale else 0)
    for p in stale:
        p.write_text(outputs[p])
        print(f'wrote {p.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
