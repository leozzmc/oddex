#!/usr/bin/env python3
"""Generate original-species data for pokeemerald-expansion from content/species/*.toml.

Inputs: content/species/*.toml (one species each), content/roles.toml (role -> species) and
content/regional_dex.toml (regional Pokedex order).

Usage (from the repository root):
  python3 tools/oddex/gen_species.py            # write generated files under game/
  python3 tools/oddex/gen_species.py --check    # exit 1 if any generated file is stale

Outputs (all committed, all marked generated):
  game/include/constants/species.h                 "oddex:species-ids" region inside enum Species
  game/include/constants/pokedex.h                 "oddex:dex-ids" / "oddex:dex-count" /
                                                   "oddex:regional-dex" regions
  game/include/constants/oddex_species.h           SPECIES_ODDEX_<ROLE> aliases
  game/src/data/pokemon/oddex_data.h               learnsets, graphics, overworld pic tables
  game/src/data/pokemon/species_info/oddex_families.h   gSpeciesInfo entries
  game/src/data/pokemon/all_learnables.json        teachable lists (only our keys are touched)
The enum entries are written in place rather than #included because the assembler path
(tools/preproc -e) parses these enums itself and cannot follow an #include inside one.
"""
